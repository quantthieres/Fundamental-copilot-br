/**
 * Safety logic for the scheduled cache refresh workflow
 * (.github/workflows/cache-refresh.yml, CLI in scripts/cache-refresh-guard.ts).
 *
 * Pure functions only — no fs/git access — so every rule is unit-testable.
 *
 *   1. Path guard        — only generated cache JSON (and optionally the
 *                          regenerated quote-only audit markdown) may be
 *                          auto-committed. Anything else fails the run.
 *   2. Timestamp filter  — a file whose only difference is its provenance
 *                          timestamp is not a real change and is restored.
 *   3. Regression guard  — the CVM/FII clients swallow network errors and
 *                          return empty data, so a refreshed cache must never
 *                          lose history or flip from available to unavailable.
 */

// ─── Paths ────────────────────────────────────────────────────────────────────

export const ALLOWED_CACHE_DIRS = [
  "src/data/cvm-cache/",
  "src/data/forecast-cache/",
  "src/data/bank-cache/",
  "src/data/fii-cache/",
  "src/data/insurance-cache/",
] as const;

export const AUDIT_DOC_PATH = "docs/coverage-audit-quote-only.md";

export interface PathGuardOptions {
  /** Allow the markdown regenerated by `npm run coverage:audit:quote-only`. */
  allowAuditDoc?: boolean;
}

export interface PathGuardResult {
  safe: string[];
  unsafe: string[];
}

/** Git status code for one changed path (porcelain v1 XY, e.g. " M", "??", "D "). */
export interface ChangedPath {
  status: string;
  path: string;
}

function normalizePath(p: string): string {
  return p.replace(/\\/g, "/").replace(/^\.\//, "");
}

export function isAllowedRefreshPath(path: string, options: PathGuardOptions = {}): boolean {
  const p = normalizePath(path);
  if (p.split("/").includes("..")) return false;
  if (options.allowAuditDoc && p === AUDIT_DOC_PATH) return true;
  // Only JSON cache files — rejects raw .zip/.csv, temp files and READMEs.
  if (!p.endsWith(".json")) return false;
  return ALLOWED_CACHE_DIRS.some(dir => p.startsWith(dir));
}

export function classifyRefreshPaths(
  paths: readonly string[],
  options: PathGuardOptions = {},
): PathGuardResult {
  const safe: string[] = [];
  const unsafe: string[] = [];
  for (const p of paths) {
    (isAllowedRefreshPath(p, options) ? safe : unsafe).push(p);
  }
  return { safe, unsafe };
}

/**
 * Parses `git status --porcelain=v1 -z --untracked-files=all`.
 * Renames/copies carry a second (original) path, which is also reported so
 * that moving a file out of a protected location is caught by the guard.
 */
export function parsePorcelainZ(output: string): ChangedPath[] {
  const fields = output.split("\0");
  const result: ChangedPath[] = [];
  for (let i = 0; i < fields.length; i++) {
    const entry = fields[i];
    if (entry.length < 4) continue;
    const status = entry.slice(0, 2);
    const path = entry.slice(3);
    result.push({ status, path });
    if (status[0] === "R" || status[0] === "C") {
      const original = fields[++i];
      if (original) result.push({ status, path: original });
    }
  }
  return result;
}

/** A refresh only adds or modifies files; deletions/renames are never expected. */
export function isUnexpectedStatus(status: string): boolean {
  return /[DRCU]/.test(status);
}

// ─── Timestamp-only changes ───────────────────────────────────────────────────

/** Top-level provenance fields written by the precompute scripts. */
export const TIMESTAMP_FIELDS = ["generatedAt", "updatedAt"] as const;

function stripTimestamps(value: unknown): unknown {
  if (!value || typeof value !== "object" || Array.isArray(value)) return value;
  const copy: Record<string, unknown> = { ...(value as Record<string, unknown>) };
  for (const f of TIMESTAMP_FIELDS) delete copy[f];
  return copy;
}

/**
 * True when two cache JSON texts differ only in their top-level timestamp.
 * Unparseable input is never considered timestamp-only.
 */
export function isTimestampOnlyJsonChange(oldText: string, newText: string): boolean {
  let oldJson: unknown;
  let newJson: unknown;
  try {
    oldJson = JSON.parse(oldText);
    newJson = JSON.parse(newText);
  } catch {
    return false;
  }
  return JSON.stringify(stripTimestamps(oldJson)) === JSON.stringify(stripTimestamps(newJson));
}

const AUDIT_DATE_LINE = /^_Gerado em \d{4}-\d{2}-\d{2} por .*_$/;

/** True when the audit markdown differs only in its "_Gerado em YYYY-MM-DD_" line. */
export function isDateOnlyAuditDocChange(oldText: string, newText: string): boolean {
  const strip = (t: string) =>
    t.split("\n").filter(line => !AUDIT_DATE_LINE.test(line)).join("\n");
  return strip(oldText) === strip(newText);
}

// ─── Data regression ──────────────────────────────────────────────────────────

type Json = Record<string, unknown>;

function arrayLength(obj: Json, key: string): number {
  const v = obj[key];
  return Array.isArray(v) ? v.length : 0;
}

function maxString(items: unknown, key: string): string | null {
  if (!Array.isArray(items)) return null;
  let max: string | null = null;
  for (const item of items) {
    const v = item && typeof item === "object" ? (item as Json)[key] : undefined;
    const s = typeof v === "number" ? String(v) : typeof v === "string" ? v : null;
    if (s !== null && (max === null || s > max)) max = s;
  }
  return max;
}

function checkNotShorter(problems: string[], oldJson: Json, newJson: Json, key: string): void {
  const before = arrayLength(oldJson, key);
  const after = arrayLength(newJson, key);
  if (after < before) problems.push(`"${key}" shrank from ${before} to ${after} entries`);
}

function checkLatestNotOlder(
  problems: string[], oldJson: Json, newJson: Json, key: string, field: string,
): void {
  const before = maxString(oldJson[key], field);
  const after = maxString(newJson[key], field);
  if (before !== null && (after === null || after < before)) {
    problems.push(`latest "${key}.${field}" went from ${before} to ${after ?? "none"}`);
  }
}

function checkStillAvailable(problems: string[], oldJson: Json, newJson: Json): void {
  if (oldJson.available !== false && newJson.available === false) {
    problems.push(`"available" flipped from true to false`);
  }
}

/**
 * Compares the committed cache JSON with the refreshed one and returns the
 * reasons the refreshed file looks degraded (empty list = acceptable).
 *
 * `oldText === null` means the file is new — only parseability is checked.
 */
export function detectCacheRegression(
  path: string,
  oldText: string | null,
  newText: string,
): string[] {
  let newJson: Json;
  try {
    newJson = JSON.parse(newText) as Json;
  } catch {
    return ["refreshed file is not valid JSON"];
  }
  if (!newJson || typeof newJson !== "object" || Array.isArray(newJson)) {
    return ["refreshed file is not a JSON object"];
  }
  if (oldText === null) return [];

  let oldJson: Json;
  try {
    oldJson = JSON.parse(oldText) as Json;
  } catch {
    return []; // previous version was broken; any valid object is an improvement
  }

  const p = normalizePath(path);
  const problems: string[] = [];

  if (p.startsWith("src/data/cvm-cache/financials/")) {
    checkNotShorter(problems, oldJson, newJson, "financials");
    checkLatestNotOlder(problems, oldJson, newJson, "financials", "fiscalYear");
  } else if (p.startsWith("src/data/cvm-cache/quarterly/")) {
    checkNotShorter(problems, oldJson, newJson, "quarterly");
  } else if (p.startsWith("src/data/cvm-cache/documents/")) {
    // The 18-month lookback legitimately drops old filings, but a cache that
    // goes from some documents to none points to a failed download.
    if (arrayLength(oldJson, "documents") > 0 && arrayLength(newJson, "documents") === 0) {
      problems.push(`"documents" went from ${arrayLength(oldJson, "documents")} to 0 entries`);
    }
  } else if (p.startsWith("src/data/forecast-cache/time-series/")) {
    checkNotShorter(problems, oldJson, newJson, "series");
  } else if (p.startsWith("src/data/forecast-cache/baseline-forecasts/")) {
    checkNotShorter(problems, oldJson, newJson, "forecasts");
  } else if (p.startsWith("src/data/bank-cache/") || p.startsWith("src/data/insurance-cache/")) {
    checkStillAvailable(problems, oldJson, newJson);
    checkNotShorter(problems, oldJson, newJson, "annual");
  } else if (p.startsWith("src/data/fii-cache/")) {
    // FII records are a rolling 24-month window, so the count may vary.
    checkStillAvailable(problems, oldJson, newJson);
    checkLatestNotOlder(problems, oldJson, newJson, "records", "referenceDate");
  }

  return problems;
}
