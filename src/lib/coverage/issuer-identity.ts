/** Non-CVM issuers that list more than one code (B3 BDR issuer roots). */
const NON_CVM_ISSUER_KEYS: Readonly<Record<string, string>> = {
  GOGL34: "b3:GOGL",
  GOGL35: "b3:GOGL",
};

export function getIssuerCvmCode(ticker: string): string | null {
  return ISSUER_CVM_CODE[ticker.toUpperCase()] ?? null;
}

/** Stable issuer key: "cvm:<CD_CVM>", a B3 issuer root for BDRs, or "ticker:<T>". */
export function getIssuerKey(ticker: string): string {
  const t = ticker.toUpperCase();
  const cvm = ISSUER_CVM_CODE[t];
  if (cvm) return `cvm:${cvm}`;
  return NON_CVM_ISSUER_KEYS[t] ?? `ticker:${t}`;
}

export function isSameIssuer(a: string, b: string): boolean {
  return getIssuerKey(a) === getIssuerKey(b);
}
